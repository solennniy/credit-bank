import test from 'node:test';
import assert from 'node:assert/strict';
const store = new Map();
globalThis.localStorage = { getItem:k=>store.get(k)||null, setItem:(k,v)=>store.set(k,v) };
const { api } = await import('../src/demo-api.js');
test('full scenario, persistence, conflict, roles and duplicate protection', async () => {
  await api.reset();
  let a = await api.create();
  assert.equal((await api.list('bank')).some(x=>x.id===a.id),false);
  a = await api.save(a.id,a.version,{confirmed:true});
  const file={name:'statement.pdf',type:'application/pdf',size:12,arrayBuffer:async()=>new TextEncoder().encode('%PDF-1.7 demo').buffer};
  a = await api.upload(a.id,a.version,file);
  const version=a.version;
  a=await api.command(a.id,a.version,'client','submit',{operationId:'op-1'});
  const again=await api.command(a.id,version,'client','submit',{operationId:'op-1'});
  assert.equal(a.number,again.number); assert.equal(a.version,again.version);
  await assert.rejects(()=>api.command(a.id,a.version,'client','review'));
  a=await api.command(a.id,a.version,'bank','review');
  await assert.rejects(()=>api.save(a.id,version,{company:'Changed'}));
  a=await api.command(a.id,a.version,'bank','request',{reason:'Полная выписка',kind:'statement',invalid:true});
  assert.equal(a.documents[0].state,'invalid');
  await assert.rejects(()=>api.command(a.id,a.version,'client','submit',{operationId:'op-2'}));
  a=await api.upload(a.id,a.version,file);
  a=await api.command(a.id,a.version,'client','submit',{operationId:'op-3'});
  a=await api.command(a.id,a.version,'bank','review');
  a=await api.command(a.id,a.version,'bank','offer',{amount:700000,months:12});
  await assert.rejects(()=>api.command(a.id,a.version,'client','accept',{offerVersion:0}));
  a=await api.command(a.id,a.version,'client','accept',{offerVersion:a.offer.version});
  a=await api.command(a.id,a.version,'bank','issue');
  assert.equal(a.status,'issued');
  await assert.rejects(()=>api.command(a.id,a.version,'bank','issue'));
  assert.ok((await api.get(a.id,'bank')).events.some(x=>x.internal));
  assert.equal((await api.get(a.id,'client')).events.some(x=>x.internal),false);
  assert.equal((await api.get(a.id,'client')).offer.amount,700000);
});
test('PDF signature is checked; corrupt storage is not silently overwritten', async()=>{
  let a=await api.create();
  await assert.rejects(()=>api.upload(a.id,a.version,{name:'x.pdf',type:'application/pdf',size:8,arrayBuffer:async()=>new TextEncoder().encode('not a pdf').buffer}));
  store.set('credit-bank-demo-v1','broken');
  await assert.rejects(()=>api.list('client'));
  assert.equal(store.get('credit-bank-demo-v1'),'broken');
  await api.reset();
});
